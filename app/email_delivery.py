"""Transactional signup email delivery over authenticated, verified TLS SMTP.

Tokens are generated by the auth router and stored only as SHA-256 digests.
The email link uses a URL fragment, never an HTTP query parameter, to avoid
leaking tokens to proxy access logs and Referer headers.
"""
import os
import smtplib
import ssl
from email.message import EmailMessage
from urllib.parse import urlsplit


def verification_required():
    # Never allow production to bypass email verification with a flag.
    return os.getenv("MARKET_MEMORY_PRODUCTION") == "1" or os.getenv("MARKET_MEMORY_EMAIL_VERIFICATION_REQUIRED") == "1"


def smtp_config():
    host = os.getenv("MARKET_MEMORY_SMTP_HOST", "").strip()
    user = os.getenv("MARKET_MEMORY_SMTP_USER", "").strip()
    password = os.getenv("MARKET_MEMORY_SMTP_PASSWORD", "")
    sender = os.getenv("MARKET_MEMORY_SMTP_FROM", "").strip()
    port_raw = os.getenv("MARKET_MEMORY_SMTP_PORT", "465")
    try:
        port = int(port_raw)
    except ValueError:
        return None
    if not (host and user and password and sender and port in (465, 587)):
        return None
    if any(c in sender for c in "\r\n") or any(c in host for c in "\r\n"):
        return None
    return host, port, user, password, sender


def delivery_ready():
    origin = os.getenv("MARKET_MEMORY_ORIGIN", "").strip()
    parts = urlsplit(origin)
    return bool(smtp_config() and parts.scheme == "https" and parts.netloc
                and not parts.username and not parts.password and parts.path in ("", "/")
                and not parts.query and not parts.fragment)


def send_verification_email(recipient, token):
    config = smtp_config()
    if not config or not delivery_ready():
        raise RuntimeError("Transactional email delivery is not configured")
    host, port, user, password, sender = config
    origin = os.environ["MARKET_MEMORY_ORIGIN"].rstrip("/")
    url = f"{origin}/#verify-email={token}"
    message = EmailMessage()
    message["From"] = sender
    message["To"] = recipient
    message["Subject"] = "Verify your Market Memory Pro email"
    message.set_content(
        "Confirm your email address to activate your Market Memory Pro account.\n\n"
        f"{url}\n\n"
        "This link expires in 30 minutes and can be used once. "
        "If you did not create an account, ignore this message.\n"
    )
    context = ssl.create_default_context()
    if port == 465:
        with smtplib.SMTP_SSL(host, port, timeout=10, context=context) as client:
            client.login(user, password)
            client.send_message(message)
    else:
        with smtplib.SMTP(host, port, timeout=10) as client:
            client.ehlo()
            client.starttls(context=context)
            client.ehlo()
            client.login(user, password)
            client.send_message(message)
